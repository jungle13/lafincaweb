// Función auxiliar para obtener qué bloques y qué cantidades descuenta un plato
export function getPlatoDeductions(codigoPos: string, cantidadVendida: number = 1): {
  bloqueKey: string;
  insumo: string;
  porciones: number;
  gramos: number;
  kilos: number;
  costo: number;
}[] {
  const receta = RECETAS_PLATOS_POS.find(r => r.codigoPos === codigoPos);
  if (!receta) return [];

  // Si tiene componentes múltiples (como Paisa especial, picadas, combos 2x1)
  if (receta.componentesMultiples && receta.componentesMultiples.length > 0) {
    return receta.componentesMultiples.map(comp => ({
      bloqueKey: comp.bloque,
      insumo: comp.comp,
      porciones: comp.cant * cantidadVendida,
      gramos: comp.gramos * cantidadVendida,
      kilos: Number(((comp.gramos * cantidadVendida) / 1000).toFixed(3)),
      costo: comp.costo * cantidadVendida
    }));
  }

  // Deducción simple
  return [{
    bloqueKey: receta.bloque,
    insumo: receta.insumoCarnico,
    porciones: receta.porcionesCount * cantidadVendida,
    gramos: receta.gramajeCrudoG * cantidadVendida,
    kilos: Number(((receta.gramajeCrudoG * cantidadVendida) / 1000).toFixed(3)),
    costo: receta.costoInsumo * cantidadVendida
  }];
}
